/// A style for ``List`` views.
public enum ListStyle: Sendable {
    /// The default list style.
    case `default`
    /// The sidebar list style.
    case sidebar
    /// The plain list style.
    case plain
    /// The grouped list style.
    case grouped
    /// The inset list style.
    case inset
    /// The bordered list style.
    case bordered
    /// The inset-grouped list style.
    case insetGrouped
}
